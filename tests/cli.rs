//! End-to-end tests of the `sdb` binary: each runs real commands in a scratch
//! directory, with its own config directory so saved connections and history
//! stay untouched.

use std::path::PathBuf;
use std::process::{Command, Output, Stdio};

/// A scratch directory, removed when dropped.
struct Scratch(PathBuf);

impl Scratch {
    fn new(name: &str) -> Scratch {
        let dir = std::env::temp_dir().join(format!("sdb-cli-{name}-{}", std::process::id()));
        let _ = std::fs::remove_dir_all(&dir);
        std::fs::create_dir_all(dir.join("config")).unwrap();
        Scratch(dir)
    }

    fn path(&self, file: &str) -> PathBuf {
        self.0.join(file)
    }

    fn run(&self, args: &[&str]) -> Output {
        Command::new(env!("CARGO_BIN_EXE_sdb"))
            .args(args)
            .current_dir(&self.0)
            .env("SDB_CONFIG_DIR", self.0.join("config"))
            .env("NO_COLOR", "1")
            .stdin(Stdio::null())
            .output()
            .unwrap()
    }

    /// Runs `sdb` and returns stdout and stderr together; panics unless it succeeds.
    fn ok(&self, args: &[&str]) -> String {
        let out = self.run(args);
        let text = output_text(&out);
        assert!(out.status.success(), "sdb {} failed:\n{text}", args.join(" "));
        text
    }

    /// Runs `sdb` and returns its output; panics if it succeeds.
    fn fails(&self, args: &[&str]) -> String {
        let out = self.run(args);
        let text = output_text(&out);
        assert!(!out.status.success(), "sdb {} should have failed:\n{text}", args.join(" "));
        text
    }

    fn edit(&self, file: &str, from: &str, to: &str) {
        let path = self.path(file);
        let text = std::fs::read_to_string(&path).unwrap();
        assert!(text.contains(from), "{file} has no {from:?}");
        std::fs::write(&path, text.replace(from, to)).unwrap();
    }

    /// `SELECT count(*) FROM table` on `db`.
    fn count(&self, db: &str, table: &str) -> u64 {
        let out = self.ok(&["query", "--db", db, &format!("SELECT count(*) AS n FROM {table}"), "-f", "csv"]);
        out.lines().nth(1).and_then(|l| l.trim().parse().ok()).unwrap_or_else(|| panic!("no count in:\n{out}"))
    }
}

impl Drop for Scratch {
    fn drop(&mut self) {
        let _ = std::fs::remove_dir_all(&self.0);
    }
}

fn output_text(out: &Output) -> String {
    String::from_utf8_lossy(&out.stdout).into_owned() + &String::from_utf8_lossy(&out.stderr)
}

const TABLES: [&str; 4] = ["users", "posts", "tags", "post_tags"];

#[test]
fn sqlite_init_push_seed_dump_restore() {
    let s = Scratch::new("pipeline");
    s.ok(&["init", "schema.dbs"]);
    s.fails(&["init", "schema.dbs"]);
    assert!(s.ok(&["check", "schema.dbs"]).contains("4 tables"));

    assert!(s.ok(&["push", "schema.dbs", "--db", "app.db", "--dry-run"]).contains("CREATE TABLE users"));
    assert!(!s.path("app.db").exists() || s.count("app.db", "sqlite_master") == 0, "dry run changes nothing");
    s.ok(&["push", "schema.dbs", "--db", "app.db", "-y"]);
    assert!(s.ok(&["push", "schema.dbs", "--db", "app.db", "-y"]).contains("already up to date"));

    s.ok(&["seed", "--db", "app.db", "-n", "12", "--seed", "7", "-y"]);
    for t in TABLES {
        assert_eq!(s.count("app.db", t), 12, "{t}");
    }

    // Dump, restore into a new file: same schema, same rows.
    s.ok(&["dump", "--db", "app.db", "-o", "dump.sql"]);
    s.ok(&["restore", "dump.sql", "--db", "copy.db", "-y"]);
    for t in TABLES {
        assert_eq!(s.count("copy.db", t), 12, "{t}");
    }
    assert!(s.ok(&["diff", "app.db", "copy.db"]).contains("identical"));
    assert!(s.ok(&["push", "schema.dbs", "--db", "copy.db", "-y"]).contains("already up to date"));
    // Restoring again needs --clean.
    s.fails(&["restore", "dump.sql", "--db", "copy.db", "-y"]);
    s.ok(&["restore", "dump.sql", "--db", "copy.db", "--clean", "-y"]);
    assert_eq!(s.count("copy.db", "posts"), 12);

    // Pull gives back the schema the file describes.
    s.ok(&["pull", "--db", "copy.db", "-o", "pulled.dbs"]);
    assert!(s.ok(&["diff", "schema.dbs", "pulled.dbs"]).contains("identical"));
    assert!(s.ok(&["sql", "pulled.dbs", "-d", "postgres"]).contains("GENERATED BY DEFAULT AS IDENTITY"));
}

#[test]
fn sqlite_migrations_keep_data() {
    let s = Scratch::new("migrate");
    s.ok(&["init", "schema.dbs"]);
    s.ok(&["push", "schema.dbs", "--db", "app.db", "-y"]);
    s.ok(&["seed", "--db", "app.db", "-n", "10", "--seed", "1", "-y"]);

    // A new column, a renamed table and a renamed column.
    s.edit("schema.dbs", "table users {", "table people was users {");
    s.edit("schema.dbs", "  email       varchar(255)  unique not null", "  mail varchar(255) unique not null was email");
    s.edit("schema.dbs", "-> users.id", "-> people.id");
    s.edit("schema.dbs", "  title       text       not null", "  title text not null\n  subtitle text");
    let plan = s.ok(&["push", "schema.dbs", "--db", "app.db", "--dry-run"]);
    assert!(plan.contains("~ table users -> people") && plan.contains("~ column people.email -> mail"), "{plan}");
    assert!(!plan.contains("DROP TABLE users"), "{plan}");
    s.ok(&["push", "schema.dbs", "--db", "app.db", "-y"]);
    assert_eq!(s.count("app.db", "people WHERE mail IS NOT NULL"), 10);
    assert_eq!(s.count("app.db", "posts"), 10);
    assert!(s.ok(&["push", "schema.dbs", "--db", "app.db", "-y"]).contains("already up to date"));

    // A dropped column is migrated too, with a warning.
    s.edit("schema.dbs", "  subtitle text\n", "");
    assert!(s.ok(&["push", "schema.dbs", "--db", "app.db", "--dry-run"]).contains("deletes its data"));
}

#[test]
fn bad_input_fails_with_a_reason() {
    let s = Scratch::new("errors");
    std::fs::write(s.path("bad.dbs"), "table t {\n  id int pk\n  name text bogus\n}\n").unwrap();
    assert!(s.fails(&["check", "bad.dbs"]).contains("line 3"));
    std::fs::write(s.path("invalid.dbs"), "table t {\n  id int pk\n  other int -> nowhere.id\n}\n").unwrap();
    s.fails(&["check", "invalid.dbs"]);
    s.fails(&["push", "invalid.dbs", "--db", "app.db", "-y"]);

    s.ok(&["init", "schema.dbs"]);
    s.ok(&["push", "schema.dbs", "--db", "app.db", "-y"]);
    std::fs::write(s.path("script.sql"), "INSERT INTO tags (name) VALUES ('a');\nINSERT INTO tags (name) VALUES ('a');\n").unwrap();
    let out = s.fails(&["exec", "script.sql", "--db", "app.db", "-1", "-y"]);
    assert!(out.contains("line 2"), "{out}");
    assert_eq!(s.count("app.db", "tags"), 0, "the transaction was rolled back");
    s.fails(&["query", "--db", "missing.db", "SELECT 1"]);
}

/// Runs against the scratch servers of `SDB_TEST_POSTGRES` / `SDB_TEST_MYSQL`
/// when set (their tables are dropped), e.g. `postgres://sdb:sdb@localhost:55432/sdb`.
#[test]
fn servers_push_seed_dump_restore() {
    for var in ["SDB_TEST_POSTGRES", "SDB_TEST_MYSQL"] {
        let Ok(url) = std::env::var(var) else {
            eprintln!("{var} not set; skipped");
            continue;
        };
        server_pipeline(&url, &var.to_ascii_lowercase());
    }
}

fn server_pipeline(url: &str, name: &str) {
    let s = Scratch::new(name);
    let empty = s.path("empty.dbs");
    std::fs::write(&empty, "").unwrap();
    let empty = empty.to_str().unwrap();
    s.ok(&["push", empty, "--db", url, "-y"]);

    s.ok(&["init", "schema.dbs"]);
    s.ok(&["push", "schema.dbs", "--db", url, "-y"]);
    assert!(s.ok(&["push", "schema.dbs", "--db", url, "-y"]).contains("already up to date"));
    s.ok(&["seed", "--db", url, "-n", "8", "--seed", "2", "-y"]);

    s.ok(&["dump", "--db", url, "-o", "dump.sql"]);
    s.ok(&["restore", "dump.sql", "--db", url, "--clean", "-y"]);
    for t in TABLES {
        assert_eq!(s.count(url, t), 8, "{t}");
    }
    assert!(s.ok(&["push", "schema.dbs", "--db", url, "-y"]).contains("already up to date"));

    // The same rows moved to SQLite. Only the data: the server's spelling of
    // checks (Postgres `= ANY (ARRAY[...])`) needn't parse in SQLite.
    s.ok(&["push", "schema.dbs", "--db", "lite.db", "-y"]);
    s.ok(&["dump", "--db", url, "-d", "sqlite", "--data-only", "-o", "lite.sql"]);
    s.ok(&["restore", "lite.sql", "--db", "lite.db", "-y"]);
    assert_eq!(s.count("lite.db", "post_tags"), 8);

    s.ok(&["push", empty, "--db", url, "-y"]);
}
