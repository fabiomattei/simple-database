/// Runs against the scratch servers of `SDB_TEST_POSTGRES` / `SDB_TEST_MYSQL`
/// when set (their tables are dropped), e.g. `postgres://sdb:sdb@localhost:55432/sdb`.
#[test]
fn servers_push_seed_dump_restore() {
    for var in ["SDB_TEST_POSTGRES", "SDB_TEST_MYSQL"] {
        let Ok(url) = std::env::var(var) else {
            eprintln!("{var} not set; skipped");
            continue;
        };
        server_pipeline(&url, &var.to_ascii_lowercase());
    }
}

fn server_pipeline(url: &str, name: &str) {
    let s = Scratch::new(name);
    let empty = s.path("empty.dbs");
    std::fs::write(&empty, "").unwrap();
    let empty = empty.to_str().unwrap();
    s.ok(&["push", empty, "--db", url, "-y"]);

    s.ok(&["init", "schema.dbs"]);
    s.ok(&["push", "schema.dbs", "--db", url, "-y"]);
    assert!(s.ok(&["push", "schema.dbs", "--db", url, "-y"]).contains("already up to date"));
    s.ok(&["seed", "--db", url, "-n", "8", "--seed", "2", "-y"]);

    s.ok(&["dump", "--db", url, "-o", "dump.sql"]);
    s.ok(&["restore", "dump.sql", "--db", url, "--clean", "-y"]);
    for t in TABLES {
        assert_eq!(s.count(url, t), 8, "{t}");
    }
    assert!(s.ok(&["push", "schema.dbs", "--db", url, "-y"]).contains("already up to date"));

    // The same rows moved to SQLite. Only the data: the server's spelling of
    // checks (Postgres `= ANY (ARRAY[...])`) needn't parse in SQLite.
    s.ok(&["push", "schema.dbs", "--db", "lite.db", "-y"]);
    s.ok(&["dump", "--db", url, "-d", "sqlite", "--data-only", "-o", "lite.sql"]);
    s.ok(&["restore", "lite.sql", "--db", "lite.db", "-y"]);
    assert_eq!(s.count("lite.db", "post_tags"), 8);

    s.ok(&["push", empty, "--db", url, "-y"]);
}

#[test]
fn check_finds_orphaned_rows() {
    let s = Scratch::new("check-orphans");
    s.ok(&["init"]);
    s.ok(&["push", "schema.dbs", "--db", "app.db", "-y"]);
    s.ok(&["seed", "--db", "app.db", "-n", "3", "--seed", "1"]);
    assert!(s.ok(&["check", "--db", "app.db"]).contains("no orphaned rows"));

    s.ok(&["query", "--db", "app.db", "PRAGMA foreign_keys = OFF; UPDATE posts SET author_id = 999 WHERE id = 1"]);
    let out = s.fails(&["check", "--db", "app.db"]);
    assert!(out.contains("1 orphaned row(s)") && out.contains("posts (author_id) -> users (id)"), "{out}");
    assert!(out.contains("999"), "the orphaned row is shown:\n{out}");
    // With the schema file: validated, then its foreign keys checked.
    let out = s.fails(&["check", "schema.dbs", "--db", "app.db", "--sample", "0"]);
    assert!(out.contains("4 tables") && out.contains("1 with problems") && !out.contains("999"), "{out}");
}
